"""
Render oracle_out_full/results.json (from probe.py) into paper/generated/results.tex,
and copy frontier.png into paper/figures/. Standard library only.

  python scripts/make_tables.py [--results oracle_out_full/results.json]
"""
import argparse
import json
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
p = argparse.ArgumentParser()
p.add_argument("--results", default=os.path.join(ROOT, "oracle_out_full", "results.json"))
p.add_argument("--tag", default="", help="e.g. 'gemma': writes results-gemma.tex with \\Gemma-prefixed macros")
a = p.parse_args()
prefix = a.tag.capitalize()
suffix = f"-{a.tag}" if a.tag else ""

with open(a.results) as f:
    r = json.load(f)
h = r["headroom"]


def tex(s):
    return str(s).replace("_", r"\_")


def num(v, fmt="{:+.4f}"):
    return "---" if v is None else fmt.format(v)


def pct(v):
    return f"{100 * v:.1f}\\%"


out = []
cmd = lambda k, v: out.append(f"\\newcommand{{\\{prefix}{k}}}{{{v}}}")
cmd("resPositions", f"{h['positions']:,}")
cmd("resBaseNLL", f"{h['base_nll']:.3f}")
cmd("resOracleGain", f"{h['oracle_nll_reduction']:.4f}")
cmd("resOraclePct", f"{h['oracle_pct_of_base']:.1f}")
cmd("resFracHelped", pct(h["frac_helped"]))
cmd("resBestStatic", f"\\op{{{tex(h['best_static']['program'])}}}")
cmd("resBestStaticDnll", num(h["best_static"]["mean_dnll"]))
cmd("resSafeSkip", pct(h["frac_tokens_with_safe_skip"]) if "frac_tokens_with_safe_skip" in h else "---")
cmd("resLagRecovery", pct(r["lag_recovery"]) if r.get("lag_recovery") is not None else "---")

rows = [f"\\op{{{o}}} & {v['oracle_gain_restricted']:.4f} & {pct(v['frac_tokens_best_op'])} & "
        f"\\op{{{tex(v['best_static'])}}} \\\\" for o, v in h["by_op"].items()]
cmd("HeadroomRows", "\n".join(rows))

rows = []
for nm, v in r["routers"].items():
    lo, hi = v["ci95"]
    rows.append(f"\\texttt{{{tex(nm)}}} & {v['dnll']:+.4f} & [{lo:+.4f}, {hi:+.4f}] & {v['auc']:.3f} & "
                f"{100 * v['edit_frac']:.1f}\\% / {v['extra_layers']:+.3f} \\\\")
cmd("RouterRows", "\n".join(rows))

rows = [f"\\texttt{{{tex(g)}}} & {v['dnll']:+.4f} & {v['extra_layers']:+.3f} \\\\" for g, v in r["ablation"].items()]
cmd("AblationRows", "\n".join(rows))

bm = r["budget_matched"]
budgets = list(next(iter(bm.values())).keys())
lines = ["\\begin{tabular}{l" + "c" * len(budgets) + "}", "\\toprule",
         "Router & " + " & ".join(f"$\\le {float(b):+.2f}$" for b in budgets) + " \\\\", "\\midrule"]
lines += [f"\\texttt{{{tex(nm)}}} & " + " & ".join(num(row[b]) for b in budgets) + " \\\\" for nm, row in bm.items()]
lines += ["\\bottomrule", "\\end{tabular}"]
cmd("BudgetTable", "\n".join(lines))

if r.get("sae_top_features"):
    top = r["sae_top_features"][:5]
    items = ", ".join(f"\\href{{{q['neuronpedia']}}}{{L{q['layer']}\\#{q['latent']}}}" for q in top)
    sae = r["routers"].get("lag_interp_sae", {}).get("dnll")
    note = f"The most predictive SAE latents on token $t-1$ are {items}."
    if sae is not None:
        note += f" Adding the selected latents to the lagged interpretable features gives $\\dnll = {sae:+.4f}$."
    cmd("SAENote", note)
else:
    cmd("SAENote", "")

os.makedirs(os.path.join(ROOT, "paper", "generated"), exist_ok=True)
with open(os.path.join(ROOT, "paper", "generated", f"results{suffix}.tex"), "w") as f:
    f.write("% Generated by scripts/make_tables.py from " + os.path.relpath(a.results, ROOT) + ". Do not edit.\n")
    f.write("\n".join(out) + "\n")

png = os.path.join(os.path.dirname(a.results), "frontier.png")
if os.path.exists(png):
    shutil.copy(png, os.path.join(ROOT, "paper", "figures", f"frontier{suffix}.png"))
print(f"wrote paper/generated/results{suffix}.tex" + (f" and paper/figures/frontier{suffix}.png" if os.path.exists(png) else ""))
